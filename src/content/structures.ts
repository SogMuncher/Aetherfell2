/** Picks a size for a recipe from two rolls in 0..1 (so a layout can know the footprint before anything is built). */
export function structureSize(def: StructureDef, r1: number, r2: number): [number, number] {
  const pick = (r: readonly [number, number], t: number): number => r[0] + Math.min(r[1] - r[0], Math.floor(t * (r[1] - r[0] + 1)));
  return [pick(def.width, r1), pick(def.depth, r2)];
}
